"""
Recommendation Engine — Brick 12.

Candidate generation ONLY. Per the Implementation Plan: "This brick
generates candidate recommendations only. It must NOT directly publish
recommendations to users." Every function here writes rows in
state=CANDIDATE and nothing else; no code path in this module ever sets
state to anything past CANDIDATE, and suitability_status is never set
here (it stays NULL — Brick 13's job).

Deterministic, rule-based only — no LLM, no AI call of any kind. This
mirrors the Brick 06 chatbot's "rule-based first" posture and keeps
candidate generation separate from external evidence and policy checks.
No free text is generated by a model here.

Inputs: Brick 09's already-computed DerivedMetric rows (the latest
computation for the user) ONLY. Deliberately does NOT read Brick 11's
spending analysis in this first version — spending analysis requires an
explicit start_date/end_date from its caller (Brick 11's own
"no silently assumed date range" rule), and a backend-triggered
generation job picking an implicit window on the user's behalf would be
exactly the kind of silent assumption Rule 1 prohibits. Spending-pattern
-based candidates (e.g. from unusual transactions) are a documented,
intentional gap, not an oversight — see README.

Rule thresholds below (3 months' emergency fund, 90% expense ratio, 10%
savings ratio, 6 months' debt-to-income) are standard, widely-cited
personal-finance rules of thumb, not a claimed regulatory or clinical
standard — same "reasonable, clearly-documented starter definition" posture
as Brick 10's category taxonomy and Brick 11's recurring/unusual-spending
heuristics. They are easy to change; changing them does not require a
migration (unlike the enum columns), just a constant here.

Idempotency: re-running generation does not create duplicate candidates.
At most one Recommendation row ever exists per (user, rule_id,
computation_id) — regenerating against an unchanged computation always
returns the existing row (whatever state it's in); only a genuinely new
computation_id (the user's profile was updated and metrics recomputed)
produces a new row for the same rule. See
_find_existing_for_computation.

Known, deliberate consequence of this design: Brick 09 computes all
metrics for a profile in one batch sharing a single computation_id, so
ANY profile update recomputes every metric under a new computation_id —
including ones whose value didn't actually change. Regenerating after
any profile update therefore produces a fresh candidate row for every
currently-firing rule, even a rule whose specific metric value is
identical to before (e.g. updating emergency_fund_amount also "changes"
the computation_id attached to the unrelated debt_to_income_ratio
metric). This is intentional: fine-grained per-metric-value diffing
would require capability Brick 09 doesn't expose, and silently assuming
an old decision still applies without a matching computation_id would
be exactly the kind of silent assumption Rule 1 prohibits. The
conservative default — re-evaluate everything after any profile change
— is the safe one.
"""

import uuid
from dataclasses import dataclass, field
from decimal import Decimal

from sqlalchemy.orm import Session

from app.models.derived_metric import DerivedMetric
from app.models.feedback import RecommendationAuditEvent
from app.models.metric_status import MetricStatus
from app.models.recommendation import (
    Recommendation,
    RecommendationCategory,
    RecommendationRiskLevel,
    RecommendationState,
)
from app.services import metrics_service

POLICY_VERSION = "v1"

# Standard personal-finance rule-of-thumb thresholds — see module docstring.
EMERGENCY_FUND_MIN_MONTHS = Decimal("3")
HIGH_EXPENSE_RATIO_THRESHOLD = Decimal("0.90")
LOW_SAVINGS_RATIO_THRESHOLD = Decimal("0.10")
HIGH_DEBT_TO_INCOME_MONTHS_THRESHOLD = Decimal("6")

RULE_CONFIDENCE = Decimal("1.00")  # deterministic threshold rules — see model docstring


class RecommendationNotFoundError(Exception):
    pass


@dataclass(frozen=True)
class SkippedRule:
    rule_id: str
    reason: str  # e.g. "metric_incomplete", "metric_not_computable", "threshold_not_met"


@dataclass
class GenerationResult:
    context_status: str  # "OK" | "NO_METRICS_COMPUTED"
    candidates: list[Recommendation] = field(default_factory=list)
    skipped: list[SkippedRule] = field(default_factory=list)


def _metric_by_name(metrics: list[DerivedMetric], name: str) -> DerivedMetric | None:
    for m in metrics:
        if m.metric_name == name:
            return m
    return None


def _find_existing_for_computation(
    db: Session, user_id: uuid.UUID, rule_id: str, computation_id: uuid.UUID
) -> Recommendation | None:
    """
    Idempotency key: (user_id, rule_id, computation_id) — checked
    regardless of the existing row's state, not just CANDIDATE.

    This went through two versions, both caught by live smoke testing
    rather than the original test suite:

    v1 matched on rule_id alone. Bug: once metrics were recomputed, an
    old CANDIDATE row for the same rule never got replaced, so a
    genuinely-changed financial situation could never produce a fresh
    candidate — only an endlessly-reused stale one.

    v2 (the fix for v1) added a computation_id match, but only against
    *open* (state=CANDIDATE) rows. Bug: once Brick 13 evaluates a
    candidate (moving it to APPROVED/CLARIFY/etc.), it's no longer
    CANDIDATE, so it stops being found — and calling /generate again
    against the SAME unchanged computation creates a brand-new
    duplicate row for a condition that was already decided. Observed
    directly: two rows for the same (rule_id, computation_id) pair, one
    APPROVED and one freshly duplicated.

    This version matches on (rule_id, computation_id) across ANY state —
    one Recommendation row ever exists per (user, rule, computation).
    Generating again before anything has actually changed always
    returns the existing row, decided or not, instead of creating a
    duplicate; a genuinely new computation_id is the only thing that
    produces a new row for the same rule.
    """
    existing = (
        db.query(Recommendation)
        .filter(Recommendation.user_id == user_id, Recommendation.rule_id == rule_id)
        .all()
    )
    target = str(computation_id)
    return next((r for r in existing if r.based_on.get("computation_id") == target), None)


def _create_candidate(
    db: Session,
    user_id: uuid.UUID,
    *,
    rule_id: str,
    category: RecommendationCategory,
    title: str,
    reason: str,
    risk_level: RecommendationRiskLevel,
    metric: DerivedMetric,
) -> Recommendation:
    existing = _find_existing_for_computation(db, user_id, rule_id, metric.computation_id)
    if existing is not None:
        return existing

    row = Recommendation(
        user_id=user_id,
        category=category,
        title=title,
        reason=reason,
        confidence=RULE_CONFIDENCE,
        risk_level=risk_level,
        state=RecommendationState.CANDIDATE,
        suitability_status=None,
        source_references=[],  # no verified external provider is configured
        based_on={
            "derived_metric_id": str(metric.id),
            "metric_name": metric.metric_name,
            "metric_value": str(metric.value),
            "computation_id": str(metric.computation_id),
            "financial_profile_id": str(metric.financial_profile_id),
        },
        rule_id=rule_id,
        policy_version=POLICY_VERSION,
    )
    db.add(row)
    db.flush()
    db.add(RecommendationAuditEvent(
        user_id=user_id,
        recommendation_id=row.id,
        from_state=None,
        to_state=RecommendationState.CANDIDATE.value,
        event_type="candidate_generated",
        metadata_json={"rule_id": rule_id, "policy_version": POLICY_VERSION, "computation_id": str(metric.computation_id)},
    ))
    db.commit()
    db.refresh(row)
    return row


def _rule_emergency_fund(db: Session, user_id: uuid.UUID, metrics: list[DerivedMetric]) -> Recommendation | SkippedRule:
    rule_id = "emergency_fund_low_coverage"
    metric = _metric_by_name(metrics, "emergency_fund_coverage_months")
    if metric is None or metric.status != MetricStatus.COMPUTED:
        return SkippedRule(rule_id, "metric_incomplete")
    if metric.value >= EMERGENCY_FUND_MIN_MONTHS:
        return SkippedRule(rule_id, "threshold_not_met")
    months = metric.value
    return _create_candidate(
        db,
        user_id,
        rule_id=rule_id,
        category=RecommendationCategory.EMERGENCY_FUND,
        title="Build up your emergency fund",
        reason=(
            f"Your emergency fund covers about {months} month(s) of expenses, "
            f"below the commonly recommended minimum of {EMERGENCY_FUND_MIN_MONTHS} months."
        ),
        risk_level=RecommendationRiskLevel.LOW,
        metric=metric,
    )


def _rule_high_expense_ratio(db: Session, user_id: uuid.UUID, metrics: list[DerivedMetric]) -> Recommendation | SkippedRule:
    rule_id = "high_expense_to_income_ratio"
    metric = _metric_by_name(metrics, "expense_to_income_ratio")
    if metric is None or metric.status != MetricStatus.COMPUTED:
        return SkippedRule(rule_id, "metric_incomplete")
    if metric.value <= HIGH_EXPENSE_RATIO_THRESHOLD:
        return SkippedRule(rule_id, "threshold_not_met")
    pct = (metric.value * Decimal("100")).quantize(Decimal("0.1"))
    return _create_candidate(
        db,
        user_id,
        rule_id=rule_id,
        category=RecommendationCategory.BUDGETING,
        title="Review your monthly budget",
        reason=(
            f"Your expenses are about {pct}% of your income, leaving little margin "
            f"against the commonly recommended maximum of {HIGH_EXPENSE_RATIO_THRESHOLD * 100}%."
        ),
        risk_level=RecommendationRiskLevel.MEDIUM,
        metric=metric,
    )


